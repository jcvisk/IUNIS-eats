CREATE TABLE IF NOT EXISTS public.roles (
                                            id BIGINT PRIMARY KEY,
                                            des VARCHAR(100) UNIQUE
    );

CREATE TABLE IF NOT EXISTS public.users (
                                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                            user_name VARCHAR(100) NOT NULL,
    password VARCHAR(255) NOT NULL,
    role INTEGER NOT NULL
    );

CREATE TABLE IF NOT EXISTS public.datos_personales (
                                                       id BIGINT PRIMARY KEY,
                                                       nombre VARCHAR(100),
    apellidos VARCHAR(100),
    edad INTEGER,
    genero VARCHAR(30),
    foto VARCHAR(255),
    user_id BIGINT
    );

CREATE TABLE IF NOT EXISTS public.roles_user (
                                                 role_id BIGINT NOT NULL,
                                                 user_id BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.platillo (
                                               id_platillo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                               nombre VARCHAR(120) NOT NULL,
    descripcion VARCHAR(500),
    precio NUMERIC(10, 2) NOT NULL,
    imagen VARCHAR(255),
    categoria VARCHAR(40) NOT NULL,
    disponibilidad BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_actualizacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP
    );

CREATE TABLE IF NOT EXISTS public.combo (
                                            id_combo BIGINT PRIMARY KEY,
                                            nombre VARCHAR(120),
    descripcion VARCHAR(500),
    precio NUMERIC(10, 2),
    imagen VARCHAR(255),
    disponibilidad BOOLEAN
    );

CREATE TABLE IF NOT EXISTS public.combo_platillo (
                                                     id_combo BIGINT NOT NULL,
                                                     id_platillo BIGINT NOT NULL,
                                                     cantidad INTEGER
);

CREATE TABLE IF NOT EXISTS public.periodo_servicio (
                                                       id_periodo BIGINT PRIMARY KEY,
                                                       fecha DATE,
                                                       limite_hora TIME,
                                                       estado_periodo VARCHAR(30)
    );

CREATE TABLE IF NOT EXISTS public.menu (
                                           id_menu BIGINT PRIMARY KEY,
                                           id_periodo BIGINT,
                                           fecha_publicacion TIMESTAMP,
                                           estado_publicacion VARCHAR(30)
    );

CREATE TABLE IF NOT EXISTS public.menu_platillo (
                                                    id_menu BIGINT NOT NULL,
                                                    id_platillo BIGINT NOT NULL,
                                                    precio_publicado NUMERIC(10, 2),
    disponibilidad BOOLEAN
    );

CREATE TABLE IF NOT EXISTS public.menu_combo (
                                                 id_menu BIGINT NOT NULL,
                                                 id_combo BIGINT NOT NULL,
                                                 precio_publicado NUMERIC(10, 2),
    disponibilidad BOOLEAN
    );

CREATE TABLE IF NOT EXISTS public.pedido (
                                             id_pedido BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                             id_usuario BIGINT,
                                             id_periodo BIGINT,
                                             fecha_hora TIMESTAMP,
                                             total NUMERIC(10, 2),
    estado VARCHAR(30)
    );

CREATE TABLE IF NOT EXISTS public.detalle_pedido (
                                                     id_detalle BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                     id_pedido BIGINT,
                                                     id_platillo BIGINT,
                                                     id_combo BIGINT,
                                                     cantidad INTEGER,
                                                     precio_aplicado NUMERIC(10, 2)
    );

CREATE TABLE IF NOT EXISTS public.historial_pedido (
                                                       id_historial BIGINT PRIMARY KEY,
                                                       id_pedido BIGINT,
                                                       id_usuario BIGINT,
                                                       estado_anterior VARCHAR(30),
    estado_nuevo VARCHAR(30),
    tipo_accion VARCHAR(50),
    fecha_hora TIMESTAMP,
    motivo VARCHAR(500)
    );

CREATE TABLE IF NOT EXISTS public.notificacion (
                                                   id_notificacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                   id_usuario BIGINT,
                                                   id_pedido BIGINT,
                                                   tipo VARCHAR(50),
    mensaje VARCHAR(500),
    fecha_hora TIMESTAMP,
    leida BOOLEAN
    );